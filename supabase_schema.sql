-- 바이브 카페 주문 테이블
-- Supabase SQL Editor에서 실행한 뒤, script.js에서 public.orders로 INSERT합니다.
CREATE TABLE IF NOT EXISTS public.orders (
  order_number BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name TEXT NOT NULL CHECK (char_length(btrim(customer_name)) > 0),
  phone_number TEXT,
  drink TEXT NOT NULL CHECK (char_length(btrim(drink)) > 0),
  size TEXT NOT NULL CHECK (size IN ('S', 'M', 'L')),
  options TEXT[] NOT NULL DEFAULT '{}',
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
  request TEXT,
  amount INTEGER NOT NULL CHECK (amount >= 0),
  ordered_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 손님이 브라우저에서 주문을 접수할 수 있도록 익명 INSERT만 허용합니다.
-- 주문 내역의 SELECT 권한은 공개하지 않습니다.
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
GRANT USAGE ON SCHEMA public TO anon;
GRANT INSERT ON TABLE public.orders TO anon;

DROP POLICY IF EXISTS "Allow anonymous order submissions" ON public.orders;
CREATE POLICY "Allow anonymous order submissions"
  ON public.orders
  FOR INSERT
  TO anon
  WITH CHECK (true);

